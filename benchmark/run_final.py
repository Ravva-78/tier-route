"""Phase 4: the single final evaluation on the frozen v3 test set (60 tasks).

Hosted calls: max_tokens=4096, reasoning_effort=low (main); always_strong is also run at 4096/default effort as a second
baseline. Local tier: max_tokens=1024. Routers escalate only on the verifier chosen on v2 DEV
(results/final/selected_verifier.json). Grading (original + formatting-robust) happens after routing.
Calls are cached so an interrupted run resumes with the same samples; it is never re-sampled.
"""
import csv
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from benchmark.live_ctx import CachedLive
from benchmark.run_eval import STRATEGIES, evaluate
from benchmark.stats import paired_bootstrap, wilson
from evaluation.grading_robust import grade_robust
from evaluation.grading_v2 import grade_task_v2
from tierroute.classifier_v2 import ComplexityClassifierV2
from tierroute.config import load_config
from tierroute.verifiers import REGISTRY

OUT = Path("results/final")
SHA = Path("benchmark/tasks_v3.sha256").read_text().split()[0]
assert hashlib.sha256(Path("benchmark/tasks_v3.json").read_bytes()).hexdigest() == SHA, "tasks_v3.json changed since freeze"
tasks = json.load(open("benchmark/tasks_v3.json", encoding="utf-8"))
ids = [t["id"] for t in tasks]
cfg = load_config()
sel = json.load(open(OUT / "selected_verifier.json"))
verifier = REGISTRY[sel["verifier"]](**sel["params"])
clf = ComplexityClassifierV2(auto_train=True)
main = CachedLive(cfg, OUT / "cache_v3_main.json", 4096, {"reasoning_effort": "low"})
dflt = CachedLive(cfg, OUT / "cache_v3_default.json", 4096, None)
ctx = main.ctx()

rows = []
for s in STRATEGIES:
    rows += [dict(r, run="main") for r in evaluate(tasks, s, verifier, ctx, classifier=clf)]
for s in ("rules", "classifier"):
    for b in (0.0, 0.25, 0.75, 1.0):
        rows += [dict(r, run="sweep") for r in evaluate(tasks, s, verifier, ctx, classifier=clf, bias=b)]
rows += [dict(r, run="main", strategy="always_strong_4096_default")
         for r in evaluate(tasks, "always_strong", None, dflt.ctx())]

# oracle: every task x every tier (primary temperature-0 draft); cheapest passing tier, unsolved -> cheapest tier
orc = {"orig": [], "robust": []}
for t in tasks:
    c = []
    for k in (0, 1, 2):
        r = ctx.generate(k, t["prompt"])
        c.append(dict(tier=k, cost=main.specs[k].cost(r.tokens_in, r.tokens_out), lat=r.latency_s,
                      orig=grade_task_v2(t, r.text)[0], robust=grade_robust(t, r.text)[0]))
    for g in ("orig", "robust"):
        ok = [x for x in c if x[g]]
        pick = min(ok, key=lambda x: x["cost"]) if ok else min(c, key=lambda x: x["cost"])
        orc[g].append(dict(task_id=t["id"], tier=pick["tier"], cost=pick["cost"], latency_s=pick["lat"],
                           solved_orig=int(any(x["orig"] for x in c)), solved_robust=int(any(x["robust"] for x in c)),
                           correct_orig=int(pick["orig"]), correct_robust=int(pick["robust"])))
for g in ("orig", "robust"):
    for r in orc[g]:
        rows.append(dict(task_id=r["task_id"], strategy=f"oracle_{g}", bias=0.5, run="main", first_tier=r["tier"],
                         final_tier=r["tier"], escalated=0, attempts=1, cost=r["cost"], latency_s=r["latency_s"],
                         tokens_out=0, finish_reason="", verdict="oracle", correct_orig=r["correct_orig"],
                         correct_robust=r["correct_robust"]))
solved = {g: {r["task_id"] for r in orc["orig"] if r[f"solved_{g}"]} for g in ("orig", "robust")}

with open(OUT / "v3_rows.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]))
    w.writeheader()
    w.writerows(rows)


def get(strategy, run="main", bias=0.5):
    d = {r["task_id"]: r for r in rows if r["strategy"] == strategy and r["run"] == run and r["bias"] == bias}
    return [d[i] for i in ids]


def lat_stats(rs):
    l = sorted(r["latency_s"] for r in rs)
    n = len(l)
    return sum(l) / n, (l[(n - 1) // 2] + l[n // 2]) / 2


names = STRATEGIES + ["always_strong_4096_default", "oracle_orig", "oracle_robust"]
ESC = ("cascade", "rules", "classifier")
L = ["# v3 final tables (generated by benchmark/run_final.py)", "",
     f"Verifier: `{sel['verifier']}` {sel['params']}. v3 SHA-256 `{SHA}`.", "",
     "## Prices used (config/models.yaml, USD per 1M tokens)", "", "| model | in | out |", "|---|---|---|"]
L += [f"| {m.name} ({m.model}) | {m.price_in_per_m} | {m.price_out_per_m} |" for m in cfg.models]
L += ["", "## Main results (60 tasks; hosted 4096 tokens, reasoning_effort=low)", "",
      "| strategy | Q orig /60 [Wilson95] | Q robust /60 [Wilson95] | cost $ | $/1000 req | escalations | workload L/M/S | mean lat s | median lat s |",
      "|---|---|---|---|---|---|---|---|---|"]
for s in names:
    rs = get(s)
    qo, qr = sum(r["correct_orig"] for r in rs), sum(r["correct_robust"] for r in rs)
    lo, hi = wilson(qo, 60)
    lo2, hi2 = wilson(qr, 60)
    c = sum(r["cost"] for r in rs)
    ml, md = lat_stats(rs)
    wl = "/".join(str(sum(1 for r in rs if r["final_tier"] == k)) for k in (0, 1, 2))
    esc = sum(r["escalated"] for r in rs) if s in ESC else "-"
    L.append(f"| {s} | {qo} [{lo * 100:.0f}-{hi * 100:.0f}%] | {qr} [{lo2 * 100:.0f}-{hi2 * 100:.0f}%] | {c:.6f} | "
             f"{c / 60 * 1000:.4f} | {esc} | {wl} | {ml:.2f} | {md:.2f} |")


def paired(a, b, key, kind):
    A, B = get(a), get(b)
    if kind == "saving":
        def f(ix):
            return 1 - sum(A[i]["cost"] for i in ix) / sum(B[i]["cost"] for i in ix)
    else:
        def f(ix):
            return (sum(A[i][key] for i in ix) - sum(B[i][key] for i in ix)) / len(ix) * 60
    return paired_bootstrap(f, 60)


def fmt(t):
    return f"{t[0] * 100:.1f}% [{t[1] * 100:.1f}, {t[2] * 100:.1f}]"


def fq(t):
    return f"{t[0]:+.1f} [{t[1]:+.1f}, {t[2]:+.1f}]"


L += ["", "## Paired bootstrap 95% CIs (10,000 resamples of the 60 tasks, seed 7)", "",
      "Saving = 1 - cost(strategy)/cost(baseline). Quality diff = strategy minus baseline, in tasks out of 60. A CI that "
      "contains 0 means the difference is not distinguishable from noise at n=60.", "",
      "| strategy | saving vs always_strong (4096 low) | saving vs always_strong (4096 default) | Q diff vs always_strong low (orig) | Q diff vs always_strong low (robust) | Q diff vs random (robust) | Q diff vs always_cheap (robust) |",
      "|---|---|---|---|---|---|---|"]
for s in ("cascade", "rules", "classifier", "random", "always_cheap"):
    L.append(f"| {s} | {fmt(paired(s, 'always_strong', None, 'saving'))} | "
             f"{fmt(paired(s, 'always_strong_4096_default', None, 'saving'))} | "
             f"{fq(paired(s, 'always_strong', 'correct_orig', 'q'))} | {fq(paired(s, 'always_strong', 'correct_robust', 'q'))} | "
             f"{fq(paired(s, 'random', 'correct_robust', 'q'))} | {fq(paired(s, 'always_cheap', 'correct_robust', 'q'))} |")

L += ["", "## Excluding tasks no model solves (defined per grader from the three tiers' primary drafts)", "",
      f"Unsolved by all three tiers: original grader {60 - len(solved['orig'])} tasks, robust grader {60 - len(solved['robust'])} tasks.",
      "", "| strategy | n (orig) | Q orig | n (robust) | Q robust | cost $ (robust set) |", "|---|---|---|---|---|---|"]
for s in names:
    rs = get(s)
    ro = [r for r in rs if r["task_id"] in solved["orig"]]
    rr = [r for r in rs if r["task_id"] in solved["robust"]]
    L.append(f"| {s} | {len(ro)} | {sum(r['correct_orig'] for r in ro)} | {len(rr)} | "
             f"{sum(r['correct_robust'] for r in rr)} | {sum(r['cost'] for r in rr):.6f} |")

L += ["", "## Bias sweep (bias 0 = save cost, 1 = quality first)", "",
      "| strategy | bias | Q orig | Q robust | cost $ | saving vs always_strong | escalations | workload L/M/S |",
      "|---|---|---|---|---|---|---|---|"]
base = sum(r["cost"] for r in get("always_strong"))
for s in ("rules", "classifier"):
    for b in (0.0, 0.25, 0.5, 0.75, 1.0):
        rs = get(s, "main", 0.5) if b == 0.5 else get(s, "sweep", b)
        c = sum(r["cost"] for r in rs)
        wl = "/".join(str(sum(1 for r in rs if r["final_tier"] == k)) for k in (0, 1, 2))
        L.append(f"| {s} | {b} | {sum(r['correct_orig'] for r in rs)} | {sum(r['correct_robust'] for r in rs)} | {c:.6f} | "
                 f"{(1 - c / base) * 100:.1f}% | {sum(r['escalated'] for r in rs)} | {wl} |")

L += ["", "## Per-tier standalone (primary draft)", "", "| tier | Q orig | Q robust | cost $ | finish=length |", "|---|---|---|---|---|"]
for k in (0, 1, 2):
    rr = [ctx.generate(k, t["prompt"]) for t in tasks]
    L.append(f"| {main.specs[k].name} | {sum(grade_task_v2(t, r.text)[0] for t, r in zip(tasks, rr))} | "
             f"{sum(grade_robust(t, r.text)[0] for t, r in zip(tasks, rr))} | "
             f"{sum(main.specs[k].cost(r.tokens_in, r.tokens_out) for r in rr):.6f} | {sum(r.finish_reason == 'length' for r in rr)} |")
(OUT / "v3_tables.md").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L))
print("live calls (main/default):", main.live_calls, dflt.live_calls)
